#!/usr/bin/env python3
"""Rebuild all report tables and equity curves from scratch (deterministic; seed in config).
  python scripts/make_report.py            # train + validation
Writes reports/summary.md, reports/equity_*.png, reports/variants_table.md.
Holdout is never touched by this script."""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy import stats as ss
from btcbot.panel import load_panel
from btcbot.variants import VARIANTS
from btcbot.evaluate import run, bounds
from btcbot.stats import summarize, by_group, deflated_sharpe, buy_and_hold, boot_ci
from btcbot.config import REPORTS

N_EVENT_TESTS = 64
KEY = ["V06", "V15", "V18"]                 # most consistent weak candidate + the two rejected candidates
df1, f, fund = load_panel()
V = pd.read_csv(REPORTS / "variants.csv")
L = ["# Result tables (generated by scripts/make_report.py)", ""]

# 1. all variants ------------------------------------------------------------------------------
cols = ["variant", "split", "mult", "n", "exp_R", "ci90_lo", "ci90_hi", "blk_ci90_lo", "pf", "win_rate", "max_dd_pct", "sharpe", "sortino",
        "lose_streak", "q_prof", "long_n", "long_exp", "short_n", "short_exp", "cost_R", "rand_mean", "rand_p", "bh_sharpe"]
tab = V[cols].sort_values(["split", "variant", "mult"])
for sp in ("train", "validation"):
    L += [f"## All variants — {sp}", "", tab[tab.split == sp].drop(columns="split").to_markdown(index=False, floatfmt=".3f"), ""]

# 2. multiple testing --------------------------------------------------------------------------
tr = V[(V.split == "train") & (V.mult == 1.0)].set_index("variant")
n_var = len(tr)
var_sr = float(tr["sr_trade"].var(ddof=1))
L += ["## Multiple-testing adjustment", "",
      f"Strategy variants tried: **{n_var}** (limit 25). Event-study tests: **{N_EVENT_TESTS}** (16 definitions x 4 horizons).",
      f"Variance of per-trade Sharpe across the {n_var} variants on Train: {var_sr:.5f}.", "",
      "| variant | split | n | exp R | per-trade SR | t | raw p (1-sided) | Bonferroni p (x variants) | Bonferroni p (x variants+event tests) | PSR(SR>0) | Deflated SR (N=variants) | Deflated SR (N=variants+tests) |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for vid in KEY + ["V20"]:
    for sp in ("train", "validation"):
        if not len(V[(V.variant == vid) & (V.split == sp)]):
            continue
        t = run(df1, f, fund, VARIANTS[vid], sp, 1.0)
        R = t["R"].to_numpy(); n = len(R); sr = R.mean() / R.std(ddof=1)
        tstat = sr * np.sqrt(n); p = 1 - ss.t.cdf(tstat, n - 1)
        d1 = deflated_sharpe(sr, n, ss.skew(R), ss.kurtosis(R, fisher=False), n_var, var_sr)
        d2 = deflated_sharpe(sr, n, ss.skew(R), ss.kurtosis(R, fisher=False), n_var + N_EVENT_TESTS, var_sr)
        L.append(f"| {vid} | {sp} | {n} | {R.mean():+.3f} | {sr:+.3f} | {tstat:+.2f} | {p:.4f} | {min(1, p*n_var):.3f} | {min(1, p*(n_var+N_EVENT_TESTS)):.3f} | {d1['psr0']:.3f} | {d1['dsr']:.3f} | {d2['dsr']:.3f} |")
L += ["", "Deflated SR = probability that the true Sharpe exceeds the best Sharpe expected from N unskilled trials (Bailey & Lopez de Prado 2014). > 0.95 would be 'significant after selection'.", ""]

# 3. detail tables + equity curves for key variants --------------------------------------------
C10, C15, CBH = "#2a78d6", "#eb6834", "#52514e"
for vid in KEY:
    L += [f"## {vid} detail", "", f"`{json.dumps(VARIANTS[vid])}`", ""]
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8), facecolor="#fcfcfb")
    for ax, sp in zip(axes, ("train", "validation")):
        a, b = bounds(sp)
        ax.set_facecolor("#fcfcfb")
        for m, col in ((1.0, C10), (1.5, C15)):
            t = run(df1, f, fund, VARIANTS[vid], sp, m)
            eq = pd.concat([pd.Series([1.0], index=[a]), pd.Series((1 + t["eq_ret"]).cumprod().to_numpy(), index=pd.DatetimeIndex(t["exit_time"]))])
            ax.step(eq.index, (eq - 1) * 100, where="post", color=col, lw=2, label=f"{m:.1f}x costs")
            ax.annotate(f"{m:.1f}x costs", (eq.index[-1], (eq.iloc[-1] - 1) * 100), xytext=(4, 0), textcoords="offset points",
                        va="center", fontsize=8, color="#0b0b0b")
            if m == 1.0:
                s = summarize(t, a, b)
                for how in ("year", "session", "side", "reason", "quarter"):
                    L += [f"**{vid} {sp} 1.0x by {how}**", "", by_group(t, how).to_markdown(floatfmt=".3f"), ""]
        bh = buy_and_hold(df1, fund, a, b)
        ax.axhline(0, color="#52514e", lw=0.6)
        ax.set_title(f"{vid} — {sp}: account return at 1% risk/trade (%)\nbuy & hold same period: {bh['ret_pct']:+.0f}% (max DD {bh['max_dd_pct']:.0f}%), not drawn",
                     fontsize=9, loc="left", color="#0b0b0b")
        ax.grid(axis="y", color="#e4e3df", lw=0.6); ax.tick_params(labelsize=8, colors="#52514e")
        for sde in ("top", "right"): ax.spines[sde].set_visible(False)
        ax.margins(x=0.12); ax.legend(frameon=False, fontsize=8, loc="upper left")
    fig.autofmt_xdate(); fig.tight_layout()
    fig.savefig(REPORTS / f"equity_{vid}.png", dpi=200); plt.close(fig)
    L += [f"![equity {vid}](equity_{vid}.png)", ""]

# 4. pooled train+validation for the family plateau ---------------------------------------------
L += ["## 1H-displacement-follow family: Train vs Validation vs pooled (descriptive; validation already seen)", "",
      "| variant | mult | train n | train exp R | val n | val exp R | pooled n | pooled exp R [90% CI] |", "|---|---|---|---|---|---|---|---|"]
for vid in ("V04", "V06", "V19", "V20"):
    for m in (1.0, 1.5):
        a = run(df1, f, fund, VARIANTS[vid], "train", m); b_ = run(df1, f, fund, VARIANTS[vid], "validation", m)
        R = np.r_[a["R"], b_["R"]]; lo, hi = boot_ci(R)
        L.append(f"| {vid} | {m} | {len(a)} | {a['R'].mean():+.3f} | {len(b_)} | {b_['R'].mean():+.3f} | {len(R)} | {R.mean():+.3f} [{lo:+.3f},{hi:+.3f}] |")
L.append("")
(REPORTS / "summary.md").write_text("\n".join(L))
print("\n".join(L[:0]) or "written reports/summary.md")
